"""Phase 0 / step 05 — consolidated dataset report.

Reads the CSVs written by steps 00–04 and writes a human-readable markdown report with
partition-level tables, an anomaly list, and data-driven suggestions for the parameters
used in later phases (candidate radius R, cap K, gap threshold, unreliable-label threshold).

Output: results/analysis/<partition>/DATASET_REPORT.md
Run:    python -m scripts.analysis.05_summary_report --partition train
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from scripts.analysis._common import out_dir, parse_args

# Radius rule: smallest radius at which >= TRIP_QUANTILE of trips have a route arc within the
# radius for >= TARGET_COVERAGE of their points. A quantile over trips (not a mean) keeps a few
# trips whose reference route covers only part of the track from dictating the radius.
TARGET_COVERAGE = 0.98
TRIP_QUANTILE = 0.90
PARTIAL_ROUTE_SHARE = 0.05   # trip flagged if > 5 % of its points are > 50 m from the route
DWELL_SPREAD_M = 1500        # far points packed within this extent ...
DWELL_TIME_SHARE = 0.30      # ... and covering this share of trip time => off-network dwell


def md_table(df: pd.DataFrame, digits: int = 3) -> str:
    """Minimal markdown table writer (no extra dependency)."""
    def fmt(v):
        if isinstance(v, (float, np.floating)):
            return "" if np.isnan(v) else f"{v:,.{digits}f}".rstrip("0").rstrip(".")
        if isinstance(v, (int, np.integer)):
            return f"{v:,}"
        return str(v)
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def stat_row(name, s: pd.Series):
    return {"quantity": name, "min": s.min(), "median": s.median(), "mean": s.mean(), "max": s.max()}


def run(partition: str, root: str | None = None, out: str | None = None) -> str:
    od = out_dir(partition, out)
    inv = pd.read_csv(od / "inventory.csv", keep_default_na=False)
    trk = pd.read_csv(od / "tracks_summary.csv")
    iss = pd.read_csv(od / "track_issues.csv", keep_default_na=False)
    gaps = pd.read_csv(od / "track_gaps.csv")
    net = pd.read_csv(od / "network_summary.csv")
    rte = pd.read_csv(od / "routes_summary.csv")
    brk = pd.read_csv(od / "route_breaks.csv")
    gvr = pd.read_csv(od / "gps_route_distance.csv")
    den = pd.read_csv(od / "candidate_density.csv")
    smp = pd.read_csv(od / "gps_route_distance_sample.csv")

    L = [f"# Dataset report — partition `{partition}`", "",
         "Generated by `python -m scripts.analysis.run_all`. All numbers below come from the CSVs in this folder.", ""]

    # 1 overview
    L += ["## 1. Overview", "",
          f"- Trips: **{len(inv)}**; GPS points: **{trk.n_points.sum():,}**",
          f"- Trips with all four files present: {int(inv[[f'{k}_present' for k in ('track','nodes','arcs','route')]].all(axis=1).astype(bool).sum())}",
          f"- Trips with format issues: {int((inv['issues'] != '').sum())}", ""]
    ov = pd.DataFrame([
        stat_row("GPS points per trip", trk.n_points),
        stat_row("duration (min)", trk.duration_s / 60),
        stat_row("path length (km)", trk.path_length_m / 1000),
        stat_row("network nodes", net.n_nodes),
        stat_row("network arcs", net.n_arcs),
        stat_row("route arcs", rte.route_n_arcs),
        stat_row("route length (km)", rte.route_length_m / 1000),
    ])
    L += [md_table(ov, 1), ""]

    # 2 track quality
    w = trk.n_points - 1
    L += ["## 2. GPS track quality", "",
          f"- Rows with NaN: {int(iss.n_nan_rows.sum())}; inf: {int(iss.n_inf_rows.sum())}; "
          f"out-of-range coordinates: {int(iss.n_out_of_range.sum())}",
          f"- lon/lat swap suspected: {int(iss.lonlat_swap_suspected.astype(str).eq('True').sum())} trips "
          f"(median share of points inside network bbox: {iss.share_in_network_bbox.median():.3f})",
          f"- Duplicate rows: {int(iss.n_duplicate_rows.sum())}; duplicate timestamps: {int(iss.n_duplicate_t.sum())}; "
          f"non-monotonic steps: {int(iss.n_non_monotonic_t.sum())}; zero-Δt steps: {int(iss.n_zero_dt.sum())}",
          f"- Share of Δt exactly 1 s (point-weighted): **{np.average(trk.dt_share_1s, weights=w):.3f}**",
          f"- Trips with a gap > 10 s: {int((trk.n_gaps_gt_10s > 0).sum())}; > 60 s: {int((trk.n_gaps_gt_60s > 0).sum())}; "
          f"> 300 s: {int((trk.n_gaps_gt_300s > 0).sum())}",
          f"- Implausible speed steps (> 70 m/s): {int(iss.filter(like='n_speed_gt').sum().sum())}",
          f"- Stationary share (speed < 0.5 m/s) median: {trk.stationary_share.median():.3f}", ""]
    big_gaps = gaps[gaps.dt_s > 300].sort_values("dt_s", ascending=False)
    if len(big_gaps):
        L += ["Largest gaps (> 300 s):", "",
              md_table(big_gaps[["trip_id", "idx_before", "dt_s", "jump_m", "implied_speed_mps"]].head(15), 1), ""]

    # 3 network
    L += ["## 3. Road networks", "",
          f"- Invalid arcs (endpoint not a node): {int(net.n_invalid_arcs.sum())}; self-loops: {int(net.n_self_loops.sum())}; "
          f"duplicate arcs: {int(net.n_duplicate_arcs.sum())}; zero-length arcs: {int(net.n_zero_length_arcs.sum())}",
          f"- Two-way share (arc u→v whose reverse exists): min {net.two_way_share.min():.2f}, "
          f"median {net.two_way_share.median():.2f}, max {net.two_way_share.max():.2f} → direction must be a feature",
          f"- Isolated nodes: {int(net.n_isolated_nodes.sum())}; dead-end nodes: {int(net.n_dead_end_nodes.sum())}",
          f"- Trips whose network has > 1 weak component: {int((net.n_weak_components > 1).sum())}; "
          f"largest strongly-connected share median {net.largest_strong_share.median():.3f}, min {net.largest_strong_share.min():.3f}",
          f"- Track points inside network bbox: min {net.track_in_network_bbox_share.min():.3f}", ""]
    L += [md_table(pd.DataFrame([stat_row("arc length p50 (m)", net.arc_len_p50_m),
                                 stat_row("arc length max (m)", net.arc_len_max_m),
                                 stat_row("network length (km)", net.network_length_km)]), 1), ""]

    # 4 routes
    L += ["## 4. Reference routes", "",
          f"- Routes present: {int(rte.route_present.astype(str).eq('True').sum())}/{len(rte)}; invalid arc ids: {int(rte.n_invalid_arc_ids.sum())}",
          f"- Continuity (arc i ends where arc i+1 starts): min {rte.continuity.min():.3f}, mean {rte.continuity.mean():.4f}; "
          f"trips with breaks: {int((rte.n_breaks > 0).sum())} (total {len(brk)} breaks, largest {brk.gap_m.max() if len(brk) else 0:.1f} m)",
          f"- Repeated arcs: {int(rte.n_repeated_arcs.sum())}; U-turns: {int(rte.n_u_turns.sum())}",
          f"- Route arcs inside largest strongly-connected component: min share {rte.share_in_largest_scc.min():.3f}",
          f"- First/last GPS point to route start/end arc p95: {rte.start_dist_m.quantile(.95):.1f} m / {rte.end_dist_m.quantile(.95):.1f} m",
          "- The route gives no per-point labels, so labels must be derived by aligning GPS points to route arcs.", ""]

    # 5 gps vs route
    q = smp.d_route_m.quantile
    L += ["## 5. GPS noise relative to the reference route", "",
          f"- Distance GPS point → nearest route arc (every 5th point): p50 {q(.5):.1f} m, p90 {q(.9):.1f} m, "
          f"p99 {q(.99):.1f} m, max {smp.d_route_m.max():.1f} m",
          f"- Points > 50 m from the route: {(smp.d_route_m > 50).mean():.4f} of sampled points",
          f"- Naive baseline — nearest arc (any direction) lies on the route for "
          f"**{gvr.nearest_arc_on_route_share.mean():.3f}** of points (mean over trips)", ""]
    agg = den.groupby("radius_m").agg(cand_mean=("cand_mean", "mean"), cand_p95=("cand_p95", "mean"),
                                      cand_max=("cand_max", "max"),
                                      route_coverage_mean=("route_within_radius_share", "mean"),
                                      route_coverage_min=("route_within_radius_share", "min")).reset_index()
    L += ["Candidate density per radius (mean over trips):", "", md_table(agg, 3), ""]

    # 6 anomalies
    anomalies = []
    partial = gvr[gvr.share_d_route_gt_50m > PARTIAL_ROUTE_SHARE]
    for r in partial.itertuples():
        dwell = r.far_spread_m <= DWELL_SPREAD_M and r.far_time_share >= DWELL_TIME_SHARE
        cause = ("OFF-NETWORK DWELL (likely parked / private ground)" if dwell
                 else "ROUTE MISMATCH / DETOUR")
        anomalies.append(f"trip {r.trip_id}: {cause} — {r.share_d_route_gt_50m:.0%} of points > 50 m from the "
                         f"reference route, spread {r.far_spread_m:.0f} m, {r.far_time_share:.0%} of trip time")
    for r in trk[trk.n_gaps_gt_300s > 0].itertuples():
        anomalies.append(f"trip {r.trip_id}: {r.n_gaps_gt_300s} gap(s) > 300 s (max {r.dt_max:.0f} s)")
    for r in rte[rte.n_breaks > 0].itertuples():
        anomalies.append(f"trip {r.trip_id}: route has {r.n_breaks} break(s), continuity {r.continuity:.3f}")
    for r in gvr[gvr.d_route_p99_m > 50].itertuples():
        anomalies.append(f"trip {r.trip_id}: GPS p99 distance to route {r.d_route_p99_m:.1f} m")
    for r in iss[iss.filter(like="n_speed_gt").sum(axis=1) > 0].itertuples():
        anomalies.append(f"trip {r.trip_id}: implausible speed steps present")
    for r in net[(net.n_nodes > 100_000) | (net.n_nodes < 1_000)].itertuples():
        anomalies.append(f"trip {r.trip_id}: unusual network size ({r.n_nodes:,} nodes)")
    L += ["## 6. Anomalies", ""] + ([f"- {a}" for a in anomalies] or ["- none found"]) + [""]

    # 7 decisions
    cov_q = den.groupby("radius_m").route_within_radius_share.quantile(1 - TRIP_QUANTILE)
    ok = cov_q[cov_q >= TARGET_COVERAGE]
    radius = int(ok.index.min()) if len(ok) else int(cov_q.index.max())
    k_cap = int(np.ceil(den[den.radius_m == radius].cand_p95.quantile(.9)))
    gap_s = 60
    unreliable_m = 50
    clean = smp[~smp.trip_id.isin(partial.trip_id)]
    L += ["## 7. Data-driven parameter suggestions", "",
          f"- **Candidate radius R = {radius} m** — smallest tested radius at which {TRIP_QUANTILE:.0%} of trips have a "
          f"route arc within R for ≥ {TARGET_COVERAGE:.0%} of their points "
          f"(per-radius {1 - TRIP_QUANTILE:.0%}-quantile coverage: "
          + ", ".join(f"{int(r)} m → {v:.3f}" for r, v in cov_q.items()) + ").",
          f"- **Candidate cap K ≈ {k_cap}** — 90th percentile (over trips) of the per-trip 95th-percentile candidate count at R.",
          f"- **Gap threshold G = {gap_s} s** — {int((trk.n_gaps_gt_60s > 0).sum())} trips contain gaps above it; "
          "the HMM chain is split there.",
          f"- **Unreliable-label threshold = {unreliable_m} m** — {(smp.d_route_m > unreliable_m).mean():.1%} of sampled "
          f"points are further than this from the route overall, but only {(clean.d_route_m > unreliable_m).mean():.1%} "
          f"once the {len(partial)} flagged trips ({', '.join(map(str, partial.trip_id)) or 'none'}) are excluded. "
          "Points beyond the threshold get `unreliable=True` and are excluded from training labels and metrics; "
          "partial-route trips should be reviewed on a folium map before deciding to drop them entirely.",
          "- Distances computed in a per-trip UTM projection (metres), never in degrees.", ""]

    text = "\n".join(L)
    (od / "DATASET_REPORT.md").write_text(text)
    print(f"  wrote {od / 'DATASET_REPORT.md'}")
    return text


if __name__ == "__main__":
    a = parse_args(__doc__)
    run(a.partition, a.data_dir, a.out_dir)
